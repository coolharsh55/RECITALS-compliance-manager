@app.get(
    "/use-cases/{use_case_id}/assessments"
)
def list_assessments(
    use_case_id: str
):

    """
    Return all compliance assessments belonging
    to one use case.
    """

    validate_use_case_id(
        use_case_id
    )

    if not use_case_exists(
        use_case_id
    ):

        raise HTTPException(
            status_code=404,
            detail="Use case not found"
        )

    resource = use_case_uri(use_case_id)

    # Newest first; every detail is OPTIONAL so older assessments still appear
    query = f"""
    PREFIX recitals: <{RECITALS}>
    PREFIX sh: <{SH}>
    PREFIX dct: <{DCT}>

    SELECT *
    WHERE {{

        ?assessment
            a recitals:ComplianceAssessment ;
            recitals:belongsToUseCase <{resource}> .

        OPTIONAL {{
            ?assessment recitals:assesses ?requirement .
        }}

        OPTIONAL {{
            ?assessment recitals:law ?law .
        }}

        OPTIONAL {{
            ?assessment recitals:article ?article .
        }}

        OPTIONAL {{
            ?assessment recitals:assessmentStatus ?status .
        }}

        OPTIONAL {{
            ?assessment recitals:hasReport ?report .
            ?report sh:conforms ?conforms .
        }}

        OPTIONAL {{
            ?assessment dct:created ?timestamp .
        }}

    }}
    ORDER BY DESC(?timestamp)
    """

    results = query_fuseki(
        query
    )

    assessments = []

    for row in results[
        "results"
    ][
        "bindings"
    ]:

        requirement = row[
            "requirement"
        ][
            "value"
        ]

        requirement_name = requirement.rsplit(
            "/",
            1
        )[-1]

        # The assessment id is the part of its URI after "assessment_"
        assessments.append({

            "assessment_id":
                row[
                    "assessment"
                ][
                    "value"
                ].rsplit(
                    "_",
                    1
                )[-1],

            "assessment_uri":
                row[
                    "assessment"
                ][
                    "value"
                ],

            "use_case_id":
                use_case_id,

            "law": row["law"]["value"].rsplit("/", 1)[-1] if "law" in row else None,

            "article": int(row["article"]["value"]) if "article" in row else None,

            "requirement":
                requirement_name,

            "status": row["status"]["value"] if "status" in row else None,

            "conforms":
                row["conforms"]["value"].lower() == "true"
                if "conforms" in row
                else None,

            "timestamp":
                row["timestamp"]["value"]
                if "timestamp" in row
                else None,

        })

    return assessments


@app.get("/use-cases/{use_case_id}/laws")
def get_use_case_laws(
    use_case_id: str
):

    """GET /use-cases/{use_case_id}/laws: list the laws that apply to a use case."""
    validate_use_case_id(use_case_id)

    if not use_case_exists(use_case_id):
        raise HTTPException(
            status_code=404,
            detail="Use case not found"
        )

    resource = use_case_uri(use_case_id)

    query = f"""
    PREFIX recitals: <{RECITALS}>

    SELECT ?law
    WHERE {{

        {resource.n3()} recitals:hasApplicableLaw ?law .

    }}
    """

    results = query_fuseki(query)

    laws = []

    for row in results["results"]["bindings"]:

        laws.append(

            row["law"]["value"].rsplit("/",1)[-1]

        )

    return laws
