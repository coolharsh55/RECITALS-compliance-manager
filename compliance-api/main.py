# Store compliance assessment
# ============================================================

def store_result(
    use_case_id: str,
    law: Law,
    article: int,
    conforms: bool,
    findings: List[Dict[str, object]]
) -> Tuple[str, str]:

    """Store an assessment, its report and its findings in Fuseki; return its id and time."""
    assessment_id = str(uuid.uuid4())

    timestamp = datetime.now(
        timezone.utc
    ).isoformat()

    assessment_uri = URIRef(
        f"{RECITALS}assessment_{assessment_id}"
    )

    report_uri = URIRef(
        f"{RECITALS}report_{assessment_id}"
    )

    use_case = use_case_uri(
        use_case_id
    )

    graph = Graph()

    graph.bind("recitals", RECITALS)
    graph.bind("sh", SH)
    graph.bind("dct", DCT)

    # ----------------------------------------------------
    # Assessment
    # ----------------------------------------------------

    graph.add((assessment_uri,
               RDF.type,
               RECITALS.ComplianceAssessment))

    graph.add((assessment_uri,
               RECITALS.assessmentId,
               Literal(assessment_id)))

    graph.add((assessment_uri,
               RECITALS.belongsToUseCase,
               use_case))

    graph.add((use_case,
               RECITALS.hasAssessment,
               assessment_uri))

    graph.add((assessment_uri,
               RECITALS.assesses,
               URIRef(f"{RECITALS}{law.value}Article{article}")))

    graph.add((assessment_uri,
               RECITALS.law,
               RECITALS[law.value]))

    graph.add((assessment_uri,
               RECITALS.article,
               Literal(article)))

    graph.add((assessment_uri,
               RECITALS.assessmentStatus,
               Literal(
                   "passed"
                   if conforms
                   else "failed"
               )))

    graph.add((assessment_uri,
               DCT.created,
               Literal(
                   timestamp,
                   datatype=XSD.dateTime
               )))

    # ----------------------------------------------------
    # Validation Report
    # ----------------------------------------------------

    graph.add((report_uri,
               RDF.type,
               RECITALS.ValidationReport))

    graph.add((report_uri,
               SH.conforms,
               Literal(
                   conforms,
                   datatype=XSD.boolean
               )))

    graph.add((assessment_uri,
               RECITALS.hasReport,
               report_uri))

    # ----------------------------------------------------
    # Findings
    # ----------------------------------------------------

    for finding in findings:

        finding_uri = URIRef(
            f"{report_uri}/finding/{uuid.uuid4()}"
        )

        graph.add((report_uri,
                   RECITALS.hasFinding,
                   finding_uri))

        graph.add((finding_uri,
                   RDF.type,
                   SH.ValidationResult))

        graph.add((finding_uri,
                   RECITALS.message,
                   Literal(finding["message"])))

        graph.add((finding_uri,
                   RECITALS.severity,
                   Literal(finding["severity"])))

        graph.add((finding_uri,
                   RECITALS.focusNode,
                   Literal(finding["focus_node"])))

        if finding.get("property"):

            graph.add((finding_uri,
                       RECITALS.property,
                       Literal(finding["property"])))

        for req in finding["requirement_ids"]:

            graph.add((finding_uri,
                       RECITALS.requirementId,
                       Literal(req)))

    # ----------------------------------------------------
    # Store graph
    # ----------------------------------------------------

    response = requests.post(

        FUSEKI_DATA_URL,

        # params={
        #     "graph": RESULTS_GRAPH
        # },

        data=graph.serialize(
            format="turtle"
        ),

        headers={
            "Content-Type":
            "text/turtle"
        },

        auth=(
            FUSEKI_USER,
            FUSEKI_PASSWORD
        ),

        timeout=15
    )

    if response.status_code not in (
        200,
        201,
        204
    ):

        raise HTTPException(
            status_code=502,
            detail="Failed to store assessment."
        )

    return assessment_id, timestamp

