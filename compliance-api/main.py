# Fetch use case RDF
# ============================================================

def fetch_graph(
    use_case_id: str
) -> Graph:

    """
    Fetch the RDF data belonging to a use case.

    The Input API stores each upload in the use case's
    named graph, so this returns everything submitted
    for the use case and nothing from other use cases.

    """

    data_graph = use_case_graph_uri(
        use_case_id
    )

    # Only the use case's own named graph, so other use cases' data is never validated
    query = f"""

    CONSTRUCT {{

        ?s ?p ?o .

    }}

    WHERE {{

        GRAPH <{data_graph}> {{

            ?s ?p ?o .

        }}

    }}

    """

    try:

        response = requests.post(

            FUSEKI_QUERY_URL,

            data=query,

            headers={
                "Content-Type":
                "application/sparql-query",
                "Accept":
                "text/turtle"
            },

            auth=(
                FUSEKI_USER,
                FUSEKI_PASSWORD
            ),

            timeout=15
        )

    except requests.RequestException:

        raise HTTPException(
            status_code=503,
            detail="Triple store unavailable"
        )

    if response.status_code != 200:

        raise HTTPException(
            status_code=502,
            detail=(
                "Failed to fetch use-case "
                "data from Fuseki"
            )
        )

    # An empty graph comes back as an empty body
    graph = Graph()

    if response.text.strip():

        graph.parse(
            data=response.text,
            format="turtle"
        )

    return graph


