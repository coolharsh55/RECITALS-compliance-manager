# Extract SHACL findings
# ============================================================

def path_label(path, *graphs):

    """The property a finding is about: its URI, or for an
    alternative path the URIs joined with " | "."""

    if path is None:
        return None

    if isinstance(path, URIRef):
        return str(path)

    # a blank node path, e.g. sh:alternativePath ( a b )
    for graph in graphs:

        if graph is None:
            continue

        alternatives = graph.value(path, SH.alternativePath)

        if alternatives is not None:
            return " | ".join(
                str(p) for p in Collection(graph, alternatives)
            )

    return None


def findings_from(
    report: Graph,
    shapes: Graph = None
) -> List[Dict[str, object]]:

    """Turn a pyshacl report into findings with requirement ids, message, severity and node."""
    findings = []

    for result in report.subjects(
        RDF.type,
        SH.ValidationResult
    ):

        requirement_ids = []

        # Property shapes carry dct:identifier on the source
        # shape; SPARQL constraints carry it on the constraint.
        for source in (
            report.value(result, SH.sourceShape),
            report.value(result, SH.sourceConstraint)
        ):

            if source is None:
                continue

            for graph in (report, shapes):

                if graph is None:
                    continue

                for value in graph.objects(
                    source,
                    DCT.identifier
                ):

                    if str(value) not in requirement_ids:
                        requirement_ids.append(
                            str(value)
                        )

        message = report.value(
            result,
            SH.resultMessage
        )

        severity = report.value(
            result,
            SH.resultSeverity
        )

        focus_node = report.value(
            result,
            SH.focusNode
        )

        result_path = report.value(
            result,
            SH.resultPath
        )

        if severity is not None:

            severity_value = str(
                severity
            ).rsplit(
                "#",
                1
            )[-1]

        else:

            severity_value = "Violation"

        findings.append({

            "requirement_ids":
                requirement_ids,

            "message":
                str(
                    message
                    or
                    "Validation failed"
                ),

            "severity":
                severity_value,

            "focus_node":
                str(
                    focus_node
                    or
                    ""
                ),

            "property":
                path_label(result_path, report, shapes)

        })

    return findings


# ============================================================
# Requirement-level results
# ============================================================

SEVERITY_RANK = {
    "Info": 0,
    "Warning": 1,
    "Violation": 2
}

# Responses say how binding a requirement is rather than using
# SHACL's severity names.
OBLIGATION = {
    "Violation": "mandatory",
    "Warning": "recommended",
    "Info": "informational"
}


def obligation(severity):
    return OBLIGATION.get(severity, "mandatory")


def with_obligation(finding):
    """A finding as returned to clients: obligation in place of severity."""
    out = {k: v for k, v in finding.items() if k != "severity"}
    out["obligation"] = obligation(finding["severity"])
    return out


def load_shapes(
    shape_file: str
) -> Graph:

    """Load a SHACL shapes file; answer 500 if it cannot be parsed."""
    shapes = Graph()

    try:

        shapes.parse(
            shape_file,
            format="turtle"
        )

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=f"Unable to load SHACL shapes: {exc}"
        )

    return shapes


def requirements_in(
    shapes: Graph
) -> Dict[str, Dict]:

    """
    Every requirement id declared in a shapes graph, with
    the messages and the highest severity of the shapes and
    constraints that carry it.
    """

    requirements = {}

    for node, identifier in shapes.subject_objects(
        DCT.identifier
    ):

        severity = shapes.value(node, SH.severity)

        # A SPARQL constraint takes the severity of its shape
        if severity is None:

            parent = shapes.value(
                predicate=SH.sparql,
                object=node
            )

            if parent is not None:
                severity = shapes.value(parent, SH.severity)

        severity = (
            str(severity).rsplit("#", 1)[-1]
            if severity is not None
            else "Violation"
        )

        entry = requirements.setdefault(
            str(identifier),
            {
                "severity": severity,
                "messages": []
            }
        )

        if SEVERITY_RANK.get(severity, 2) > SEVERITY_RANK.get(entry["severity"], 2):
            entry["severity"] = severity

        message = shapes.value(node, SH.message)

        if message is not None and str(message) not in entry["messages"]:
            entry["messages"].append(str(message))

    return requirements


def natural_key(
    text: str
):

    """Sort key that orders ids like A30-1-2 before A30-1-10."""
    return [
        int(part) if part.isdigit() else part
        for part in re.split(r"(\d+)", text)
    ]


def requirement_results(
    shapes: Graph,
    findings: List[Dict]
) -> Tuple[List[Dict], Dict[str, int]]:

    """
    One entry per requirement in the shapes, marked passed,
    failed (a Violation was found) or warning (only Warnings
    were found), with the findings behind it.
    """

    requirements = requirements_in(shapes)

    # Group the findings by requirement id; findings without an id are grouped as "unlabelled"
    found = {}

    for finding in findings:

        for requirement_id in finding["requirement_ids"] or ["unlabelled"]:

            found.setdefault(
                requirement_id,
                []
            ).append(finding)

            requirements.setdefault(
                requirement_id,
                {
                    "severity": finding["severity"],
                    "messages": []
                }
            )

    results = []

    summary = {
        "total": 0,
        "passed": 0,
        "failed": 0,
        "warnings": 0
    }

    # A requirement fails on any Violation, is a warning on Warnings only, and passes otherwise
    for requirement_id in sorted(requirements, key=natural_key):

        entry = requirements[requirement_id]

        requirement_findings = found.get(requirement_id, [])

        if any(f["severity"] == "Violation" for f in requirement_findings):
            status = "failed"
            summary["failed"] += 1

        elif requirement_findings:
            status = "warning"
            summary["warnings"] += 1

        else:
            status = "passed"
            summary["passed"] += 1

        summary["total"] += 1

        results.append({

            "id": requirement_id,

            "status": status,

            "obligation": obligation(entry["severity"]),

            "message": " / ".join(entry["messages"]),

            "findings": [
                {
                    "message": f["message"],
                    "obligation": obligation(f["severity"]),
                    "focus_node": f["focus_node"],
                    "property": f["property"]
                }
                for f in requirement_findings
            ]

        })

    return results, summary


