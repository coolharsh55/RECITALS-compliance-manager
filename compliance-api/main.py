def use_case_uri(use_case_id: str) -> URIRef:

    """
    Return the URI used by the Input API for a use case.

    Example:

    UC1
    ->
    http://example.org/recitals/UC1
    """

    return URIRef(
        f"http://example.org/recitals/{use_case_id}"
    )


def use_case_graph_uri(use_case_id: str) -> URIRef:

    """
    Return the named graph in which the Input API stores
    the RDF submitted for a use case.
    """

    return URIRef(
        f"http://example.org/recitals/graph/{use_case_id}"
    )


def validate_assessment_id(
    assessment_id: str
) -> None:

    """
    Assessment ids are UUIDs generated by store_result.
    Reject anything else before it reaches a SPARQL query.
    """

    try:
        uuid.UUID(assessment_id)
    except ValueError:
        raise HTTPException(
            status_code=404,
            detail="Assessment not found"
        )


def validate_use_case_id(
    use_case_id: str
) -> None:

    """
    Validate the use case identifier.
    """

    if not re.fullmatch(
        r"[A-Za-z0-9_-]{1,80}",
        use_case_id
    ):

        raise HTTPException(
            status_code=422,
            detail=(
                "use_case_id may contain only "
                "letters, numbers, underscores, "
                "and hyphens"
            )
        )


# ============================================================
# Fuseki query helper
# ============================================================

def query_fuseki(
    query: str
) -> Dict:

    """
    Execute a SPARQL SELECT query against Fuseki.
    """

    try:

        response = requests.post(

            FUSEKI_QUERY_URL,

            data=query,

            headers={
                "Content-Type":
                "application/sparql-query",
                "Accept":
                "application/sparql-results+json"
            },

            auth=(
                FUSEKI_USER,
                FUSEKI_PASSWORD
            ),

            timeout=15
        )

    except requests.RequestException:

        raise HTTPException(
            status_code=503,
            detail="Triple store unavailable"
        )

    if response.status_code != 200:

        raise HTTPException(
            status_code=502,
            detail=(
                "Triple store query failed: "
                + response.text
            )
        )

    try:

        return response.json()

    except ValueError:

        raise HTTPException(
            status_code=502,
            detail="Invalid response from triple store"
        )


# ============================================================
# Get existing use cases
# ============================================================

def get_existing_use_cases() -> List[Dict]:

    """
    Retrieve use cases already stored in the
    triplestore.

    This is deliberately based on the RDF representation
    created by the Input API.

    Example:

    recitals:UC1
        a recitals:UseCase ;
        rdfs:label "Employee Recruitment" ;
        recitals:hasApplicableLaw recitals:GDPR .
    """

    query = f"""

    PREFIX recitals: <{RECITALS}>
    PREFIX rdfs: <{RDFS}>

    SELECT ?uc ?label ?law

    WHERE {{

        ?uc a recitals:UseCase ;
            rdfs:label ?label .

        OPTIONAL {{

            ?uc recitals:hasApplicableLaw ?law .

        }}

    }}

    ORDER BY ?uc

    """

    results = query_fuseki(query)

    # Rows repeat per law, so collect each use case once and gather its laws
    use_cases = {}

    for row in results[
        "results"
    ][
        "bindings"
    ]:

        uri = row["uc"]["value"]

        use_case_id = uri.rsplit(
            "/",
            1
        )[-1]

        if use_case_id not in use_cases:

            use_cases[
                use_case_id
            ] = {

                "use_case_id":
                    use_case_id,

                "label":
                    row["label"]["value"],

                "applicable_laws":
                    [],

                "uri":
                    uri

            }

        if "law" in row:

            law_uri = row[
                "law"
            ][
                "value"
            ]

            law = law_uri.rsplit(
                "/",
                1
            )[-1]

            if law not in use_cases[
                use_case_id
            ][
                "applicable_laws"
            ]:

                use_cases[
                    use_case_id
                ][
                    "applicable_laws"
                ].append(law)

    return list(
        use_cases.values()
    )


