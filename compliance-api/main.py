@app.get(
    "/assessments/{assessment_id}/report"
)
def get_assessment_report(
    assessment_id: str
):

    """GET /assessments/{assessment_id}/report: a stored assessment with every requirement's result."""
    validate_assessment_id(assessment_id)

    query = f"""
    PREFIX recitals: <{RECITALS}>
    PREFIX sh: <http://www.w3.org/ns/shacl#>
    PREFIX dct: <http://purl.org/dc/terms/>

    SELECT *
    WHERE {{

        BIND(
            <{RECITALS}assessment_{assessment_id}>
            AS ?assessment
        )

        ?assessment
            a recitals:ComplianceAssessment ;
            recitals:belongsToUseCase ?use_case ;
            recitals:assesses ?requirement ;
            recitals:law ?law ;
            recitals:article ?article ;
            recitals:assessmentStatus ?status ;
            recitals:hasReport ?report ;
            dct:created ?timestamp .

        ?report
            a recitals:ValidationReport ;
            sh:conforms ?conforms .

        OPTIONAL {{

            ?report
                recitals:hasFinding ?finding .

            OPTIONAL {{
                ?finding recitals:message ?message .
            }}

            OPTIONAL {{
                ?finding recitals:severity ?severity .
            }}

            OPTIONAL {{
                ?finding recitals:focusNode ?focusNode .
            }}

            OPTIONAL {{
                ?finding recitals:property ?property .
            }}

            OPTIONAL {{
                ?finding recitals:requirementId ?requirementId .
            }}
        }}
    }}
    ORDER BY ?finding
    """

    results = query_fuseki(query)

    bindings = results["results"]["bindings"]

    if not bindings:

        raise HTTPException(
            status_code=404,
            detail="Assessment not found"
        )

    first = bindings[0]

    findings = []

    by_uri = {}

    violations = 0
    warnings = 0

    for row in bindings:

        if "finding" not in row:
            continue

        finding_uri = row["finding"]["value"]

        # A finding with several requirement ids comes back
        # as one row per id.
        if finding_uri in by_uri:

            if "requirementId" in row:
                by_uri[finding_uri]["requirement_ids"].append(
                    row["requirementId"]["value"]
                )

            continue

        severity = (
            row["severity"]["value"]
            if "severity" in row
            else "Violation"
        )

        if severity.lower() == "violation":
            violations += 1

        elif severity.lower() == "warning":
            warnings += 1

        finding = {

            "requirement_id":
                row["requirementId"]["value"]
                if "requirementId" in row
                else None,

            "requirement_ids":
                [row["requirementId"]["value"]]
                if "requirementId" in row
                else [],

            "severity":
                severity,

            "message":
                row["message"]["value"]
                if "message" in row
                else None,

            "focus_node":
                row["focusNode"]["value"]
                if "focusNode" in row
                else None,

            "property":
                row["property"]["value"]
                if "property" in row
                else None

        }

        by_uri[finding_uri] = finding

        findings.append(finding)

    law = first["law"]["value"].rsplit("/", 1)[-1]

    article = int(first["article"]["value"])

    shape_file = ASSESSMENTS.get((law, article))

    # An article that is no longer assessed has no shapes to list
    # passed requirements from; show the findings it recorded.
    requirements, requirement_summary = requirement_results(
        load_shapes(shape_file) if shape_file else Graph(),
        findings
    )

    return {

        "assessment": {

            "id":
                assessment_id,

            "uri":
                first["assessment"]["value"],

            "timestamp":
                first["timestamp"]["value"],

            "status":
                first["status"]["value"],

            "conforms":
                first["conforms"]["value"].lower() == "true"

        },

        "use_case": {

            "id":
                first["use_case"]["value"].rsplit("/", 1)[-1],

            "uri":
                first["use_case"]["value"]

        },

        "requirement": {

            "law":
                first["law"]["value"].rsplit("/",1)[-1],

            "article":
                int(first["article"]["value"]),

            "identifier":
                first["requirement"]["value"].rsplit("/",1)[-1]

        },

        "summary": {

            "total_findings":
                len(findings),

            "mandatory":
                violations,

            "recommended":
                warnings

        },

        "requirement_summary":
            requirement_summary,

        "requirements":
            requirements,

        "findings":
            [with_obligation(f) for f in findings]

    }


