def run_check(use_case_id: str, law: Law, article: int):

    # --------------------------------------------------------
    # Validate use case id
    # --------------------------------------------------------

    validate_use_case_id(use_case_id)

    # --------------------------------------------------------
    # Check use case exists
    # --------------------------------------------------------

    if not use_case_exists(use_case_id):
        raise HTTPException(
            status_code=404,
            detail="Use case not found"
        )

    # --------------------------------------------------------
    # Check selected law belongs to the use case
    # --------------------------------------------------------

    use_case_laws = get_use_case_laws(use_case_id)

    if law.value not in use_case_laws:
        raise HTTPException(
            status_code=400,
            detail=f"{law.value} is not applicable to {use_case_id}"
        )

    # --------------------------------------------------------
    # Check article belongs to the selected law
    # --------------------------------------------------------

    allowed_articles = get_articles_for_law(law)

    if article not in allowed_articles:
        raise HTTPException(
            status_code=400,
            detail=(
                f"Article {article} is not available for "
                f"{law.value}. "
                f"Available articles: {allowed_articles}"
            )
        )

    # --------------------------------------------------------
    # Get SHACL shape
    # --------------------------------------------------------

    shape_file = ASSESSMENTS.get(
        (
            law.value,
            article
        )
    )

    if shape_file is None:
        raise HTTPException(
            status_code=400,
            detail=(
                f"No assessment available for "
                f"{law.value} Article {article}"
            )
        )

    # --------------------------------------------------------
    # Fetch RDF graph
    # --------------------------------------------------------

    data_graph = fetch_graph(use_case_id)

    if len(data_graph) == 0:
        raise HTTPException(
            status_code=404,
            detail="Use case contains no RDF data"
        )

    # --------------------------------------------------------
    # Load SHACL graph
    # --------------------------------------------------------

    shapes = load_shapes(shape_file)

    # --------------------------------------------------------
    # Execute validation
    # --------------------------------------------------------

    try:

        conforms, report, _ = validate(
            data_graph,
            shacl_graph=shapes,
            inference="rdfs",
            debug=False
        )

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=f"SHACL validation failed: {exc}"
        )

    # pyshacl reports invalid shapes by returning the error
    # in place of the report graph rather than raising it.
    if not isinstance(report, Graph):

        raise HTTPException(
            status_code=500,
            detail=f"SHACL validation failed: {report}"
        )

    # --------------------------------------------------------
    # Extract findings
    # --------------------------------------------------------

    findings = findings_from(report, shapes)

    requirements, summary = requirement_results(
        shapes,
        findings
    )

    # --------------------------------------------------------
    # Store assessment
    # --------------------------------------------------------

    assessment_id, timestamp = store_result(
        use_case_id=use_case_id,
        law=law,
        article=article,
        conforms=conforms,
        findings=findings
    )

    # --------------------------------------------------------
    # Response
    # --------------------------------------------------------

    return {

        "assessment_id": assessment_id,

        "use_case_id": use_case_id,

        "law": law.value,

        "article": article,

        "requirement": f"{law.value}Article{article}",

        "status":
            "passed" if conforms else "failed",

        "conforms": conforms,

        "timestamp": timestamp,

        "summary": summary,

        "requirements": requirements,

        "findings": [with_obligation(f) for f in findings]

    }


